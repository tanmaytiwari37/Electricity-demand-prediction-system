import type { DataSource, FeederStatus, ForecastMethod, RiskLevel, WeatherSource } from '../../types/api.ts'
import { feederMeta, riskMeta } from '../../utils/format.ts'

/** Provenance vocabulary. Every page states its sources once, in one quiet
 *  line (SourceLine); a Badge is used only where a single figure needs its
 *  own caveat (allocation, assumption, simulation). */
export type ProvenanceKind =
  | 'demo'
  | 'real'
  | 'model'
  | 'heuristic'
  | 'live'
  | 'cache'
  | 'demo_weather'
  | 'analog_weather'
  | 'simulated'
  | 'allocated'
  | 'assumption'
  | 'backtest'
  | 'rules'

const STYLES: Record<ProvenanceKind, { label: string; dot: string; text: string; title: string }> = {
  demo: { label: 'Simulated demo data', dot: 'bg-warning', text: 'text-warning', title: 'Synthetic history generated by the app. Not real Delhi load data.' },
  real: { label: 'Historical Delhi load', dot: 'bg-series-aqua', text: 'text-ink-2', title: 'Loaded from the operator-supplied dataset of recorded Delhi system load.' },
  model: { label: 'ML model forecast', dot: 'bg-series-blue', text: 'text-ink-2', title: 'Output of the trained demand model.' },
  heuristic: { label: 'Heuristic forecast', dot: 'bg-ink-3', text: 'text-ink-2', title: 'Same-hour average of the last 7 days with a temperature adjustment. No trained model is loaded yet.' },
  live: { label: 'Live weather', dot: 'bg-series-aqua', text: 'text-ink-2', title: 'Open-Meteo forecast fetched at startup.' },
  cache: { label: 'Cached weather', dot: 'bg-warning', text: 'text-ink-2', title: 'Open-Meteo unreachable; using the last cached forecast.' },
  demo_weather: { label: 'Simulated weather', dot: 'bg-warning', text: 'text-warning', title: 'Synthetic weather forecast (demo mode, Open-Meteo unavailable).' },
  analog_weather: { label: 'Analog weather', dot: 'bg-warning', text: 'text-warning', title: 'Weather from the same hours 52 weeks earlier, because the dataset does not end today.' },
  simulated: { label: 'Simulated feeder data', dot: 'bg-warning', text: 'text-warning', title: 'System demand split by configured DISCOM share. Real feeder telemetry is not public.' },
  allocated: { label: 'Allocated, not measured', dot: 'bg-series-magenta', text: 'text-series-magenta', title: 'The system-level forecast split by configured DISCOM share ratios. Our data contains no feeder or DISCOM telemetry.' },
  assumption: { label: 'Assumption', dot: 'bg-series-violet', text: 'text-ink-2', title: 'Configurable planning assumption, not a measured or official limit.' },
  backtest: { label: '1-h backtest', dot: 'bg-series-blue', text: 'text-ink-2', title: 'What the model would have predicted one hour ahead using true history.' },
  rules: { label: 'Rule-based advice', dot: 'bg-ink-3', text: 'text-ink-2', title: 'System-generated recommendation. Not an operational instruction.' },
}

export function Badge({ kind, small }: { kind: ProvenanceKind; small?: boolean }) {
  const s = STYLES[kind]
  return (
    <span title={s.title} className={`inline-flex items-center gap-1.5 whitespace-nowrap font-medium ${s.text} ${small ? 'text-[10.5px]' : 'text-[11px]'}`}>
      <span className={`h-1.5 w-1.5 rounded-full ${s.dot}`} aria-hidden />
      {s.label}
    </span>
  )
}

/** One line listing the sources behind a page. Replaces per-panel pills. */
export function SourceLine({ kinds, className = '' }: { kinds: ProvenanceKind[]; className?: string }) {
  return (
    <div className={`flex flex-wrap items-center gap-x-4 gap-y-1 ${className}`}>
      {kinds.map((k) => <Badge key={k} kind={k} />)}
    </div>
  )
}

export const historyKind = (s: DataSource): ProvenanceKind => (s === 'real' ? 'real' : 'demo')
export const methodKind = (m: ForecastMethod): ProvenanceKind => (m === 'ml_model' ? 'model' : 'heuristic')
export const weatherKind = (w: WeatherSource): ProvenanceKind =>
  w === 'live' ? 'live' : w === 'cache' ? 'cache' : w === 'historical_analog' ? 'analog_weather' : 'demo_weather'

/** Short header word for the data source: DEMO / HISTORICAL / LIVE. */
export const sourceWord = (history: DataSource, weather?: WeatherSource): string =>
  history === 'demo' ? 'DEMO' : weather === 'live' ? 'LIVE' : 'HISTORICAL'

export function RiskPill({ level, size = 'md' }: { level: RiskLevel; size?: 'sm' | 'md' | 'lg' }) {
  const m = riskMeta[level]
  const sz = size === 'lg' ? 'px-2.5 py-1 text-xs' : size === 'sm' ? 'px-1.5 py-0.5 text-[10px]' : 'px-2 py-0.5 text-[11px]'
  return (
    <span className={`inline-flex items-center gap-1.5 rounded-sm border font-bold tracking-[0.08em] ${m.bg} ${m.border} ${m.text} ${sz}`}>
      <span aria-hidden className="text-[0.8em]">{m.icon}</span>
      {m.label}
    </span>
  )
}

export function StatusPill({ status }: { status: FeederStatus }) {
  const m = feederMeta[status]
  return (
    <span className={`inline-flex items-center gap-1.5 rounded-sm border px-2 py-0.5 text-[10px] font-bold tracking-[0.08em] ${m.bg} ${m.border} ${m.text}`}>
      <span aria-hidden className="text-[0.8em]">{m.icon}</span>
      {m.label}
    </span>
  )
}
