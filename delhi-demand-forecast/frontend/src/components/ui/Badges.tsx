import type { DataSource, FeederStatus, ForecastMethod, RiskLevel, WeatherSource } from '../../types/api.ts'
import { feederMeta, riskMeta } from '../../utils/format.ts'

/** Provenance badges. Every major section carries one so simulated data is
 *  never mistaken for real Delhi operational data. */
export type ProvenanceKind =
  | 'demo'
  | 'real'
  | 'model'
  | 'heuristic'
  | 'live'
  | 'cache'
  | 'demo_weather'
  | 'analog_weather'
  | 'simulated'
  | 'allocated'
  | 'assumption'
  | 'backtest'
  | 'rules'

const STYLES: Record<ProvenanceKind, { label: string; cls: string; title: string }> = {
  demo: { label: 'SIMULATED DEMO DATA', cls: 'border-warning/50 bg-warning/10 text-warning', title: 'Synthetic history generated by the app. Not real Delhi load data.' },
  real: { label: 'REAL HISTORICAL', cls: 'border-series-aqua/50 bg-series-aqua/10 text-series-aqua', title: 'Loaded from the operator-supplied dataset.' },
  model: { label: 'MODEL PREDICTION', cls: 'border-series-blue/50 bg-series-blue/10 text-series-blue', title: 'Output of the trained demand model.' },
  heuristic: { label: 'HEURISTIC ESTIMATE', cls: 'border-ink-3/50 bg-surface-2 text-ink-2', title: 'Same-hour average of the last 7 days with a temperature adjustment. No trained model is loaded yet.' },
  live: { label: 'LIVE WEATHER', cls: 'border-series-aqua/50 bg-series-aqua/10 text-series-aqua', title: 'Open-Meteo forecast fetched at startup.' },
  cache: { label: 'CACHED WEATHER', cls: 'border-warning/50 bg-warning/10 text-warning', title: 'Open-Meteo unreachable; using the last cached forecast.' },
  demo_weather: { label: 'SIMULATED WEATHER', cls: 'border-warning/50 bg-warning/10 text-warning', title: 'Synthetic weather forecast (demo mode, Open-Meteo unavailable).' },
  analog_weather: { label: 'HISTORICAL ANALOG WEATHER', cls: 'border-warning/50 bg-warning/10 text-warning', title: 'Weather from the same hours 52 weeks earlier, because the dataset does not end today.' },
  simulated: { label: 'SIMULATED SPLIT', cls: 'border-warning/50 bg-warning/10 text-warning', title: 'System demand split by configured DISCOM share. Real feeder telemetry is not public.' },
  allocated: { label: '≈ PROPORTIONAL ALLOCATION', cls: 'border-dashed border-series-magenta/70 bg-series-magenta/10 text-series-magenta', title: 'Not measured. The system-level forecast split by configured DISCOM share ratios (approximations of publicly reported DISCOM peak demands). Our data contains no feeder or DISCOM telemetry.' },
  assumption: { label: 'ASSUMPTION', cls: 'border-series-violet/50 bg-series-violet/10 text-series-violet', title: 'Configurable planning assumption, not a measured or official limit.' },
  backtest: { label: '1-H BACKTEST', cls: 'border-series-blue/50 bg-series-blue/10 text-series-blue', title: 'What the model would have predicted one hour ahead using true history. More optimistic than a real multi-hour forecast.' },
  rules: { label: 'RULE-BASED ADVICE', cls: 'border-ink-3/50 bg-surface-2 text-ink-2', title: 'System-generated recommendation. Not an operational instruction.' },
}

export function Badge({ kind, small }: { kind: ProvenanceKind; small?: boolean }) {
  const s = STYLES[kind]
  return (
    <span
      title={s.title}
      className={`inline-flex items-center whitespace-nowrap rounded border font-semibold tracking-wider ${s.cls} ${small ? 'px-1.5 py-0.5 text-[10px]' : 'px-2 py-0.5 text-[11px]'}`}
    >
      {s.label}
    </span>
  )
}

export const historyKind = (s: DataSource): ProvenanceKind => (s === 'real' ? 'real' : 'demo')
export const methodKind = (m: ForecastMethod): ProvenanceKind => (m === 'ml_model' ? 'model' : 'heuristic')
export const weatherKind = (w: WeatherSource): ProvenanceKind =>
  w === 'live' ? 'live' : w === 'cache' ? 'cache' : w === 'historical_analog' ? 'analog_weather' : 'demo_weather'

export function RiskPill({ level, size = 'md' }: { level: RiskLevel; size?: 'sm' | 'md' | 'lg' }) {
  const m = riskMeta[level]
  const sz = size === 'lg' ? 'px-3 py-1 text-sm' : size === 'sm' ? 'px-1.5 py-0.5 text-[10px]' : 'px-2 py-0.5 text-xs'
  return (
    <span className={`inline-flex items-center gap-1.5 rounded border font-bold tracking-wider ${m.bg} ${m.border} ${m.text} ${sz}`}>
      <span aria-hidden>{m.icon}</span>
      {m.label}
    </span>
  )
}

export function StatusPill({ status }: { status: FeederStatus }) {
  const m = feederMeta[status]
  return (
    <span className={`inline-flex items-center gap-1.5 rounded border px-2 py-0.5 text-[11px] font-bold tracking-wider ${m.bg} ${m.border} ${m.text}`}>
      <span aria-hidden>{m.icon}</span>
      {m.label}
    </span>
  )
}
